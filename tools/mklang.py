#!/usr/bin/env python3
"""Build the program texts header from a language file.

usage: tools/mklang.py LANG OUT.h      (reads lang/en.txt + lang/LANG.txt)

lang/en.txt is the master list: every key must be there. lang/LANG.txt translates them:
missing keys fall back to English (warning), unknown keys and broken texts stop the build.
Format, one per line:   KEY = "text with \\n and \\" escapes"      # comments allowed
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LINE = re.compile(r'^([A-Z][A-Z0-9_]*)\s*=\s*"((?:[^"\\]|\\.)*)"\s*(?:#.*)?$')
FMT = re.compile(r'%[-+ #0]*\d*(?:\.\d+)?l?[a-zA-Z%]')
WIDTH = 40                      # Atari / C64 screen

def load(path):
    texts, errors = {}, []
    for no, raw in enumerate(path.read_text(encoding='latin-1').splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        m = LINE.match(line)
        if not m:
            errors.append('%s:%d: expected  KEY = "text"' % (path.name, no))
            continue
        key, body = m.groups()
        bad = re.search(r'\\[^n"\\]', body)
        if bad:
            errors.append('%s:%d: %s: only \\n, \\" and \\\\ are allowed (found %s)' % (path.name, no, key, bad.group(0)))
            continue
        if key in texts:
            errors.append('%s:%d: %s twice' % (path.name, no, key))
        texts[key] = (body.replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\'), no)
    return texts, errors

def check(name, key, text, en, no):
    errs, warns = [], []
    where = '%s:%d: %s' % (name, no, key)
    if any(not (32 <= ord(c) < 127 or c == '\n') for c in text):
        errs.append(where + ': plain ASCII only (umlauts: ae oe ue ss)')
    if FMT.findall(text) != FMT.findall(en):
        errs.append(where + ': placeholders %s, English has %s' % (FMT.findall(text), FMT.findall(en)))
    if key.startswith('KEY_') and not re.fullmatch('[a-z]', text):
        errs.append(where + ': answer key must be one lower-case letter')
    if key.startswith('RAW_') and re.search('[a-z]', text):
        errs.append(where + ': upper case only (shown before the caller picked a machine)')
    for seg in text.split('\n'):
        if len(FMT.sub('', seg)) > WIDTH and len(seg) > max(len(s) for s in en.split('\n')):
            warns.append(where + ': line longer than %d characters: "%s"' % (WIDTH, seg))
    return errs, warns

def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

def main():
    lang, out = sys.argv[1], pathlib.Path(sys.argv[2])
    en, errors = load(ROOT / 'lang' / 'en.txt')
    warnings = []
    texts = dict(en)
    if lang != 'en':
        path = ROOT / 'lang' / (lang + '.txt')
        if not path.exists():
            sys.exit('mklang: lang/%s.txt not found' % lang)
        tr, e = load(path)
        errors += e
        for key in tr:
            if key not in en:
                errors.append('%s.txt:%d: %s is not in lang/en.txt' % (lang, tr[key][1], key))
        for key in en:
            if key not in tr:
                warnings.append('%s.txt: %s missing - English used' % (lang, key))
            else:
                texts[key] = tr[key]
    for key, (text, no) in texts.items():
        name = (lang if key in texts and lang != 'en' and texts[key] is not en[key] else 'en') + '.txt'
        e, w = check(name, key, text, en[key][0], no)
        errors += e
        warnings += w
    for w in warnings:
        print('mklang: warning: ' + w, file=sys.stderr)
    if errors:
        for e in errors:
            print('mklang: error: ' + e, file=sys.stderr)
        sys.exit(1)
    body = ['/* Generated by tools/mklang.py from lang/%s.txt - do not edit. */' % lang,
            '#ifndef LANG_H', '#define LANG_H', '']
    body += ['#define L_%-20s %s' % (k, c_string(t)) for k, (t, _) in texts.items()]
    body += ['', '#endif', '']
    new = '\n'.join(body)
    if not out.exists() or out.read_text() != new:      # unchanged header: no rebuild
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(new)

main()
